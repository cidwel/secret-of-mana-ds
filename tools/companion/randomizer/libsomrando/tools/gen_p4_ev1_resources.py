#!/usr/bin/env python3
"""Turns the upstream pokedex resource used by the Open World PokedexEvent into a C file, outside the repository.

  gen_p4_ev1_resources.py <upstream SoMRandomizer folder> <output .c>

The data (Resources/pokedata3.xml) is third-party pokedex text and is therefore generated at build time from a checkout of
Moppu/SecretOfManaRandomizer, like gen_resources.py does for the vineshroom tiles; it is never committed.  Only what the C# reads is kept:
for every child of the root, the id attribute and the text of its direct name and description children (the last one wins, as in the C#).
Original tool of this repository (LGPL-2.1+).
"""
import pathlib
import sys
import xml.etree.ElementTree as ET


def cstr(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch in '"\\':
            out.append("\\" + ch)
        elif 32 <= o < 127:
            out.append(ch)
        else:
            raise SystemExit("non-ASCII character in pokedata3.xml: %r" % ch)
    return '"' + "".join(out) + '"'


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    src = pathlib.Path(sys.argv[1]) / "Resources" / "pokedata3.xml"
    root = ET.parse(src).getroot()
    rows = []
    for p in root:
        name = desc = ""
        for ch in p:
            if ch.tag == "name":
                name = ch.text or ""
            if ch.tag == "description":
                desc = ch.text or ""
        rows.append((p.get("id"), name, desc))
    out = ["/* Generated by gen_p4_ev1_resources.py from the upstream Moppu/SecretOfManaRandomizer v1.49 resources.  Do not edit, do not commit. */",
           '#include "sr_p4_ev1.h"', "", "const struct sr_p4_ev1_pokemon sr_res_pokedex[] = {"]
    for i, n, d in rows:
        out.append("  {%s, %s, %s}," % (cstr(i), cstr(n), cstr(d)))
    out += ["};", "const int sr_res_pokedex_count = %d;" % len(rows)]
    pathlib.Path(sys.argv[2]).write_text("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
