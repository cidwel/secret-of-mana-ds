#!/usr/bin/env python3
"""Generates src/sr_p3_ruins_data.[ch]: the byte tables and ReplacementMapSegments of the ruins floor generator, mechanically parsed from the
upstream C# (processing/ancientcave/mapgen/ruins/ (*.cs) and the npcIds table of AncientCaveMapGenerator.cs).  Original work of this repository
(LGPL-2.1+).

  gen_p3_ruins_data.py UPSTREAM_PROJECT_DIR OUT_DIR
"""
import pathlib
import re
import sys

P = "sr_p3_ruins_"
SOURCES = [("gen", "ruins/RuinsGenerator.cs"), ("court", "ruins/RuinsCourtyard.cs"), ("ins", "ruins/InsideRooms.cs"),
           ("out", "ruins/OutsideRooms.cs"), ("base", "AncientCaveMapGenerator.cs")]
ONLY_BASE = {"npcIds"}


def clean(text):
    text = text.lstrip("﻿")
    return re.sub(r"//[^\n]*", "", text)


def nums(body):
    items = [t.strip() for t in body.replace("\n", " ").split(",") if t.strip()]
    out = []
    for t in items:
        if not re.fullmatch(r"(0x[0-9A-Fa-f]+|\d+)", t):
            return None
        out.append(int(t, 0))
    return out


def main():
    root = pathlib.Path(sys.argv[1]) / "processing/ancientcave/mapgen"
    out = pathlib.Path(sys.argv[2])
    arrays, segs = [], []   # (cname, values) / (cname, fields, dataname)
    for tag, rel in SOURCES:
        text = clean((root / rel).read_text(encoding="utf-8"))
        for m in re.finditer(r"\bbyte\[\]\s+(\w+)\s*=\s*new byte\[\]\s*\{([^}]*)\}\s*;", text):
            if tag == "base" and m.group(1) not in ONLY_BASE:
                continue
            v = nums(m.group(2))
            if v is not None:
                arrays.append((tag + "_" + m.group(1), v))
        if tag == "base":
            continue
        names = re.findall(r"ReplacementMapSegment\s+(\w+)\s*=\s*new ReplacementMapSegment\(\)\s*;", text)
        for nm in names:
            f = {"x": 0, "y": 0, "w": 0, "h": 0}
            data = None
            for m in re.finditer(r"\b%s\.(x|y|w|h)\s*=\s*(-?\d+)\s*;" % nm, text):
                f[m.group(1)] = int(m.group(2))
            for m in re.finditer(r"\b%s\.data\s*=\s*new byte\[\]\s*\{([^}]*)\}\s*;" % nm, text):
                data = nums(m.group(1))
            segs.append((tag + "_" + nm, f, data))
    h = ["/* libsomrando: ruins floor generator data tables, GENERATED by tools/gen_p3_ruins_data.py from the upstream C#.  LGPL-2.1 or later.",
         " * Derived from processing/ancientcave/mapgen/ruins/ (*.cs) (Author: Moppleton). */",
         "#ifndef SR_P3_RUINS_DATA_H", "#define SR_P3_RUINS_DATA_H", '#include "sr_p3_ac.h"', ""]
    c = ["/* libsomrando: ruins floor generator data tables, GENERATED by tools/gen_p3_ruins_data.py (do not edit).  LGPL-2.1 or later.",
         " * Derived from processing/ancientcave/mapgen/ruins/ (*.cs) (Author: Moppleton). */",
         '#include "sr_p3_ruins_data.h"', ""]
    for nm, v in arrays:
        h.append("extern const uint8_t %s%s[%d];" % (P, nm, len(v)))
        c.append("const uint8_t %s%s[%d] = {%s};" % (P, nm, len(v), ", ".join(str(x) for x in v)))
    c.append("")
    for nm, f, d in segs:
        if d is not None:
            assert len(d) == f["w"] * f["h"], nm
            c.append("static const uint8_t %sd_%s[%d] = {%s};" % (P, nm, len(d), ", ".join(str(x) for x in d)))
        h.append("extern const struct ac_segment %s%s;" % (P, nm))
        c.append("const struct ac_segment %s%s = {%d, %d, %d, %d, %s};" % (
            P, nm, f["x"], f["y"], f["w"], f["h"], ("%sd_%s" % (P, nm)) if d is not None else "0"))
    h += ["", "#endif", ""]
    (out / "sr_p3_ruins_data.h").write_text("\n".join(h))
    (out / "sr_p3_ruins_data.c").write_text("\n".join(c) + "\n")
    print("arrays %d segments %d" % (len(arrays), len(segs)))


main()
