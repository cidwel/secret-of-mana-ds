#include <string.h>

#include "sr_core.h"
#include "sr_p2.h"

static void emit_n(struct sr_ctx *c, const uint8_t *b, size_t n) {
  for (size_t i = 0; i < n; i++) sr_emit(c, b[i]);
}
#define EMIT(...) do { const uint8_t b_[] = {__VA_ARGS__}; emit_n(c, b_, sizeof b_); } while (0)

/* writes the 4 byte JSL (22 lo hi bank) at off with the target being the current working offset */
static void jsl_here(struct sr_ctx *c, int off) {
  sr_poke(c, off, 0x22);
  sr_poke(c, off + 1, c->working_offset);
  sr_poke(c, off + 2, c->working_offset >> 8);
  sr_poke(c, off + 3, (c->working_offset >> 16) + 0xC0);
}

/* the speed clamp shared by both animation hooks */
static void emit_speed_clamp(struct sr_ctx *c, int min_speed) {
  EMIT(0xE0, 0x00, 0x06, 0xB0, 0x01, 0x6B);   /* CPX #0600; BGE +1; RTL */
  EMIT(0xC9, 0x00, 0xD0, 0x01, 0x6B);          /* CMP #00; BNE +1; RTL */
  EMIT(0xC9, min_speed, 0xB0, 0x02, 0xA9, min_speed);
  EMIT(0xC9, 0x10 - min_speed, 0x90, 0x02, 0xA9, 0x10 - min_speed);
  EMIT(0x6B);
}

int sr_hack_faster_enemies(struct sr_ctx *c) {
  if (!sr_settings_get_bool(c->settings, "aggEnemies")) return 0;
  int no_stamina = sr_settings_get_bool(c->settings, "attacksForever");
  const int min_speed = 3;

  sr_ensure_space_in_bank(&c->working_offset, 0x200);

  int table = c->working_offset, table1 = c->working_offset + 1;
  for (int i = 0; i < 0x70; i++) {
    int v = c->out[0x2AF05 + i];
    if (v == 0x01) v = 0x02;
    if (v == 0x81) v = 0x82;
    if (v == 0x02) v = 0x03;
    if (v == 0x82) v = 0x83;
    sr_emit(c, v);
  }

  jsl_here(c, 0x1D698);
  sr_poke(c, 0x1D69C, 0xEA);
  EMIT(0xE0, 0x00, 0x06, 0xB0, 0x06, 0x85, 0x0F, 0xB9, 0x00, 0xC7, 0x6B);
  EMIT(0x48, 0xBD, 0x80, 0xE1, 0xC9, 0x54, 0x90, 0x07, 0x68, 0x85, 0x0F, 0xB9, 0x00, 0xC7, 0x6B);
  EMIT(0x68, 0x85, 0x0F, 0xDA, 0xBB, 0xBF, table, table >> 8, (table >> 16) + 0xC0, 0xFA, 0x6B);

  jsl_here(c, 0x1D6BD);
  sr_poke(c, 0x1D6C1, 0xEA);
  EMIT(0xE0, 0x00, 0x06, 0xB0, 0x06, 0xB9, 0x01, 0xC7, 0xC9, 0x80, 0x6B);
  EMIT(0xBD, 0x80, 0xE1, 0xC9, 0x54, 0x90, 0x06, 0xB9, 0x01, 0xC7, 0xC9, 0x80, 0x6B);
  EMIT(0xDA, 0xBB, 0xBF, table1, table1 >> 8, (table1 >> 16) + 0xC0, 0xFA, 0xC9, 0x80, 0x6B);

  /* animation timing hooks */
  jsl_here(c, 0x1D557);
  EMIT(0xA5, 0x0C, 0x29, 0x0F);
  emit_speed_clamp(c, min_speed);

  jsl_here(c, 0x1D56F);
  sr_poke(c, 0x1D573, 0xEA);
  sr_poke(c, 0x1D574, 0xEA);
  EMIT(0xA5, 0x0C, 0x4A, 0x4A, 0x4A, 0x4A);
  emit_speed_clamp(c, min_speed);

  for (int i = 0x100000; i < 0x110000; i++)
    if (c->out[i] == 0x30 && c->out[i + 1] == 0x80 && c->out[i + 2] == 0x6D && c->out[i + 3] == 0x00) sr_poke(c, i + 3, 0xFF);

  sr_poke(c, 0x1207F, 0xEA);
  sr_poke(c, 0x12080, 0xEA);
  sr_poke(c, 0xF528, 0xEA);
  sr_poke(c, 0xF529, 0xEA);

  jsl_here(c, 0xF942);
  sr_poke(c, 0xF946, 0xEA);
  if (!no_stamina) EMIT(0xE0, 0x00, 0x06, 0xB0, 0x06, 0x69, 0x32, 0x9D, 0xED, 0xE1, 0x6B);
  EMIT(0xA9, 0x00, 0x9D, 0xED, 0xE1, 0x6B);

  jsl_here(c, 0x2C248);
  sr_poke(c, 0x2C24C, 0xEA);
  if (!no_stamina) EMIT(0xE0, 0x00, 0x06, 0xB0, 0x06, 0x69, 0x32, 0x9D, 0xED, 0xE1, 0x6B);
  EMIT(0xA9, 0x00, 0x9D, 0xED, 0xE1, 0x6B);
  return 1;
}
