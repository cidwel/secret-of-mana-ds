#!/usr/bin/env python3
"""Emits the flavor table of LimeSlimeFlavors.cs (insertion order, expressions kept verbatim) as a C header.

  gen_p4_hmisc_lime.py <upstream SoMRandomizer folder> <out .h>

Original tool of this repository (LGPL-2.1+).
"""
import pathlib
import re
import sys


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    text = (pathlib.Path(sys.argv[1]) / "processing/hacks/openworld/LimeSlimeFlavors.cs").read_text(encoding="utf-8-sig")
    out = ["/* Generated by tools/gen_p4_hmisc_lime.py from LimeSlimeFlavors.cs (Author: Moppleton).  Do not edit. */",
           "static const struct { const char *name; double v[8]; } sr_p4_hmisc_flavors[] = {"]
    n = 0
    for name, body in re.findall(r'\{\s*"(\w+)",\s*new double\[\]\s*\{(.*?)\}\.ToList\(\)\s*\}', text, re.S):
        vals = [v.strip() for v in body.replace("\n", " ").split(",") if v.strip()]
        assert len(vals) == 8, name
        out.append('  {"%s", {%s}},' % (name, ", ".join(vals)))
        n += 1
    out.append("};")
    out.append("#define SR_P4_HMISC_N_FLAVORS %d" % n)
    pathlib.Path(sys.argv[2]).write_text("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
