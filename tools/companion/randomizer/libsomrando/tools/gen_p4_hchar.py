#!/usr/bin/env python3
"""Generates src/sr_p4_hk_char_*.c from the upstream C# of the Open World character hacks (Moppu/SecretOfManaRandomizer v1.49).

  gen_p4_hchar.py <upstream SoMRandomizer folder> <out src dir>

Translates line by line the statement shapes these four classes use (byte patching, string compares of the class names, a few EventScript
calls, private helper methods).  Anything else stops the run with the offending line.  Derived from the upstream files; LGPL-2.1+.
"""
import os
import re
import sys

FILES = [
    ("sr_p4_hk_char_classes.c", "processing/hacks/openworld/CharacterClasses.cs", "CharacterClasses", "sr_p4_hack_character_classes"),
    ("sr_p4_hk_char_join.c", "processing/openworld/CharacterJoinChanges.cs", "CharacterJoinChanges", "sr_p4_hack_character_join_changes"),
    ("sr_p4_hk_char_rabite.c", "processing/hacks/openworld/InvincibleRabite.cs", "InvincibleRabite", "sr_p4_hack_invincible_rabite"),
    ("sr_p4_hk_char_whip.c", "processing/hacks/openworld/FastWhipPosts.cs", "FastWhipPosts", "sr_p4_hack_fast_whip_posts"),
]

HEADER = '''/* libsomrando: C port of Moppu/SecretOfManaRandomizer v1.49 (commit 1404b7b).  LGPL-2.1 or later, see sr_core.h and COPYING.LIB.
 *
 * Derived from SoMRandomizer/%(rel)s (Author: Moppleton).  Translated to C 2026-10-18.
 * Generated by tools/gen_p4_hchar.py; do not edit by hand.
 */
#include <string.h>

#include "sr_p4.h"

#define E(v) sr_emit(c, (v))
#define P(off, v) sr_poke(c, (off), (v))

'''

WD_HELPERS = '''static const char *wd_get(struct sr_ctx *c, const char *key) {
  const char *v = sr_work_get(c, key);
  return v ? v : "";
}

'''
WD_BOOL = '''static int wd_bool(struct sr_ctx *c, const char *key) {
  char b[8];
  size_t n = 0;
  const char *v = wd_get(c, key);
  while (*v == ' ') v++;
  for (; *v && *v != ' ' && n < 7; v++) b[n++] = (char)((*v >= 'A' && *v <= 'Z') ? *v + 32 : *v);
  b[n] = 0;
  return !strcmp(b, "yes") || !strcmp(b, "true") || !strcmp(b, "1");
}

'''


def load_consts(src):
    consts = {}
    for rel in ["config/settings/OpenWorldSettings.cs", "processing/openworld/OpenWorldClassSelection.cs",
                "processing/openworld/OpenWorldCharacterSelection.cs", "processing/common/EventFlags.cs",
                "processing/common/SomVanillaValues.cs"]:
        text = open(os.path.join(src, rel), encoding="utf-8-sig").read()
        cls = os.path.basename(rel)[:-3]
        for m in re.finditer(r'public (?:const|static) (?:string|byte|int) (\w+) = ("[^"]*"|0x[0-9A-Fa-f]+|\d+);', text):
            consts[cls + "." + m.group(1)] = m.group(2)
    text = open(os.path.join(src, "processing/common/EventCommandEnum.cs"), encoding="utf-8-sig").read()
    for m in re.finditer(r'public static EventCommandEnum (\w+) = new EventCommandEnum\((0x[0-9A-Fa-f]+)\);', text):
        consts["EventCommandEnum." + m.group(1)] = m.group(2)
    return consts


class Gen:
    def __init__(self, consts):
        self.consts = consts
        self.events = set()
        self.uses_bool = False

    def const(self, ref):
        if ref not in self.consts:
            raise SystemExit("unknown constant " + ref)
        return self.consts[ref]

    def match_bracket(self, s, start):
        depth = 0
        for i in range(start, len(s)):
            if s[i] == "[":
                depth += 1
            elif s[i] == "]":
                depth -= 1
                if depth == 0:
                    return i
        raise SystemExit("unbalanced bracket: " + s)

    def conv(self, e):
        e = e.strip()
        e = re.sub(r"settings\.getInt\((\w+)\.(\w+)\)", lambda m: 'sr_settings_get_int(c->settings, %s)' % self.const(m.group(1) + "." + m.group(2)), e)
        e = re.sub(r"settings\.getBool\((\w+)\.(\w+)\)", lambda m: 'sr_settings_get_bool(c->settings, %s)' % self.const(m.group(1) + "." + m.group(2)), e)
        e = re.sub(r"context\.workingData\.get\((\w+)\.(\w+)\)", lambda m: 'wd_get(c, %s)' % self.const(m.group(1) + "." + m.group(2)), e)

        def wdb(m):
            self.uses_bool = True
            return 'wd_bool(c, %s)' % self.const(m.group(1) + "." + m.group(2))
        e = re.sub(r"context\.workingData\.getBool\((\w+)\.(\w+)\)", wdb, e)
        e = re.sub(r"EventCommandEnum\.(\w+)\.Value", lambda m: self.const("EventCommandEnum." + m.group(1)), e)
        e = re.sub(r"\b(EventFlags|SomVanillaValues)\.(\w+)", lambda m: self.const(m.group(1) + "." + m.group(2)), e)
        e = e.replace("context.workingOffset", "c->working_offset")
        e = e.replace("(byte)", "(uint8_t)")
        for name, fn in (("outRom", "sr_peek"), ("origRom", "sr_peek_orig")):
            while True:
                i = e.find(name + "[")
                if i < 0:
                    break
                j = self.match_bracket(e, i + len(name))
                e = e[:i] + "%s(c, %s)" % (fn, e[i + len(name) + 1:j]) + e[j + 1:]
        e = re.sub(r'(\w+) == ("[^"]*")', r"(strcmp(\1, \2) == 0)", e)
        e = re.sub(r'(\w+) != ("[^"]*")', r"(strcmp(\1, \2) != 0)", e)
        e = re.sub(r"\btrue\b", "1", e)
        e = re.sub(r"\bfalse\b", "0", e)
        return e

    def stmt(self, code, ind):
        """Translate one statement (no trailing comment). Returns C text."""
        m = re.fullmatch(r"outRom\[context\.workingOffset\+\+\]\s*=\s*(.+);", code)
        if m:
            if "workingOffset" in m.group(1):
                raise SystemExit("emit reads workingOffset: " + code)
            return "E(%s);" % self.conv(m.group(1))
        m = re.fullmatch(r"outRom\[(.+?)\]\s*(\|=|&=|=)\s*(.+);", code)
        if m:
            if m.group(2) == "=":
                return "P(%s, %s);" % (self.conv(m.group(1)), self.conv(m.group(3)))
            op = m.group(2)[0]
            idx = self.conv(m.group(1))
            return "P(%s, sr_peek(c, %s) %s (%s));" % (idx, idx, op, self.conv(m.group(3)))
        m = re.fullmatch(r"CodeGenerationUtils\.ensureSpaceInBank\(ref context\.workingOffset,\s*(.+)\);", code)
        if m:
            return "sr_ensure_space_in_bank(&c->working_offset, %s);" % self.conv(m.group(1))
        m = re.fullmatch(r"(int|byte|bool|ushort|string)\s+(\w+)\s*=\s*(.+);", code)
        if m:
            ty = {"int": "int", "byte": "uint8_t", "bool": "int", "ushort": "uint16_t", "string": "const char *"}[m.group(1)]
            sep = "" if ty.endswith("*") else " "
            return "%s%s%s = %s;" % (ty, sep, m.group(2), self.conv(m.group(3)))
        m = re.fullmatch(r"byte\[\]\s+(\w+)\s*=\s*new byte\[\]\s*\{(.*)\};", code)
        if m:
            return "const uint8_t %s[] = {%s};" % (m.group(1), m.group(2).strip())
        m = re.fullmatch(r"int\[\]\s+(\w+)\s*=\s*new int\[\]\s*\{(.*)\};", code)
        if m:
            return "const int %s[] = {%s};" % (m.group(1), m.group(2).strip())
        m = re.fullmatch(r"int\[\]\s+(\w+)\s*=\s*new int\[(\d+)\];", code)
        if m:
            return "int %s[%s] = {0};" % (m.group(1), m.group(2))
        m = re.fullmatch(r"(\w+(?:\[\w+\])?)\s*=\s*(.+);", code)
        if m and "(" not in m.group(1):
            return "%s = %s;" % (m.group(1), self.conv(m.group(2)))
        m = re.fullmatch(r"(if|else if)\s*\((.*)\)", code)
        if m:
            return "%s (%s)" % (m.group(1), self.conv(m.group(2)))
        m = re.fullmatch(r"for\s*\((.*);(.*);(.*)\)", code)
        if m:
            init = re.sub(r"^int ", "int ", m.group(1).strip())
            return "for (%s; %s; %s)" % (init, self.conv(m.group(2)), m.group(3).strip())
        if code in ("else", "{", "}"):
            return code
        if code == "return true;":
            return "return 1;"
        if code == "return false;":
            return "return 0;"
        m = re.fullmatch(r"(setJumpLocation|make\w+)\(outRom(?:, context)?(?:,\s*(.*))?\);", code)
        if m:
            args = (", " + self.conv(m.group(2))) if m.group(2) else ""
            if m.group(1) == "setJumpLocation":
                return "set_jump_location(c%s);" % args
            return "%s(c%s);" % (snake(m.group(1)), args)
        # EventScript forms
        m = re.fullmatch(r"EventScript (\w+) = new EventScript\(\);", code)
        if m:
            return "struct sr_bytes *%s;" % m.group(1)
        m = re.fullmatch(r"context\.replacementEvents\[(\w+)\] = (\w+);", code)
        if m:
            return "%s = sr_event_new(c, %s);" % (m.group(2), m.group(1))
        m = re.fullmatch(r"(\w+)\.Add\((.*)\);", code)
        if m:
            return "sr_bytes_push(c, %s, %s);" % (m.group(1), self.conv(m.group(2)))
        m = re.fullmatch(r"(\w+)\.(SetFlag|IncrFlag|DecrFlag)\((.*)\);", code)
        if m:
            fn = {"SetFlag": "sr_ev_set_flag", "IncrFlag": "sr_ev_incr_flag", "DecrFlag": "sr_ev_decr_flag"}[m.group(2)]
            return "%s(c, %s, %s);" % (fn, m.group(1), self.conv(m.group(3)))
        m = re.fullmatch(r"(\w+)\.Jsr\((.*)\);", code)
        if m:
            return "sr_ev_jsr(c, %s, %s);" % (m.group(1), self.conv(m.group(2)))
        m = re.fullmatch(r"(\w+)\.End\(\);", code)
        if m:
            return "sr_ev_end(c, %s);" % m.group(1)
        m = re.fullmatch(r"(\w+)\.Logic\(([^,]+),([^,]+),([^,]+),\s*EventScript\.GetJumpCmd\((.*)\)\);", code)
        if m:
            return ("{ uint8_t cmd[2]; sr_ev_jump_cmd(%s, cmd); sr_ev_logic(c, %s, %s, %s, %s, cmd); }" %
                    (self.conv(m.group(5)), m.group(1), self.conv(m.group(2)), self.conv(m.group(3)), self.conv(m.group(4))))
        raise SystemExit("unsupported statement: " + code)

    def body(self, text):
        out = []
        depth = 1
        in_block = False
        for raw in text.split("\n"):
            line = raw.strip()
            if not line:
                continue
            if in_block or line.startswith("/*"):
                out.append("  " * depth + (line if line.startswith(("/*", "*")) else "*" + line if False else line))
                in_block = "*/" not in line
                continue
            if line.startswith("//"):
                out.append("  " * depth + line)
                continue
            code, _, cm = line.partition("//")
            code = code.strip()
            cm = ("  //" + cm) if cm else ""
            if not code:
                continue
            if code.startswith("}"):
                depth -= 1
            out.append("  " * depth + self.stmt(code, depth) + cm)
            if code.endswith("{") or code == "{":
                depth += 1
        return "\n".join(out)


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def method_bodies(text):
    res = []
    for m in re.finditer(r"(protected override bool process|private void (\w+))\(([^)]*)\)\s*\{", text):
        i, depth = m.end(), 1
        while depth:
            ch = text[i]
            depth += (ch == "{") - (ch == "}")
            i += 1
        res.append((m.group(2) or "process", m.group(3), text[m.end():i - 1]))
    return res


def main():
    src, outdir = sys.argv[1:3]
    consts = load_consts(src)
    for fname, rel, cls, fn in FILES:
        text = open(os.path.join(src, rel), encoding="utf-8-sig").read()
        g = Gen(consts)
        parts, protos = [], []
        for name, params, body in method_bodies(text):
            code = g.body(body)
            if name == "process":
                parts.append("int %s(struct sr_ctx *c) {\n%s\n}\n" % (fn, code))
                continue
            plist = [p.strip() for p in params.split(",")][1 if name == "setJumpLocation" else 2:]
            cp = []
            for p in plist:
                ty, nm = p.split()
                cp.append(("int " if ty == "int" else "uint8_t " if ty == "byte" else "const char *") + nm)
            unused = "".join("  (void)%s;\n" % p.split()[-1].lstrip("*") for p in cp
                             if not re.search(r"\b%s\b" % p.split()[-1].lstrip("*"), body))
            if name == "setJumpLocation":
                head = "static void set_jump_location(struct sr_ctx *c, %s) {\n" % ", ".join(cp)
            else:
                head = "static void %s(struct sr_ctx *c%s) {\n" % (snake(name), "".join(", " + x for x in cp))
            parts.append(head + unused + code + "\n}\n")
            protos.append(head.rstrip(" {\n") + ";")
        joined = "\n".join(parts)
        for m in re.finditer(r"^ *const int (\w+)\[\] = \{[^}]*\};\n", joined, re.M):
            if len(re.findall(r"\b%s\b" % m.group(1), joined)) == 1:
                parts = [x.replace(m.group(0), "") for x in parts]
        out = HEADER % {"rel": rel}
        if "wd_get" in "".join(parts):
            out += WD_HELPERS
        if g.uses_bool:
            out += WD_BOOL
        # helper methods first (the C# calls them from process)
        helpers = [p for p in parts if p.startswith("static")]
        procs = [p for p in parts if not p.startswith("static")]
        out += "\n".join(protos) + ("\n\n" if protos else "")
        out += "\n".join(procs) + "\n" + "\n".join(helpers)
        open(os.path.join(outdir, fname), "w").write(out)
        print("wrote", fname, len(out.split("\n")), "lines")


if __name__ == "__main__":
    main()
