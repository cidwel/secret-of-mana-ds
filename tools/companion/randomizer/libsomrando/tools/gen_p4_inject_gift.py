#!/usr/bin/env python3
"""Generates src/sr_p4_ow_gift_data.h: the gift tables of GiftModeProcessing.cs and GiftDeliveryIntroEvent.cs of the upstream project (LGPL-2.1).

  gen_p4_inject_gift.py <upstream SoMRandomizer folder> <output .h>

Original tool of this repository (LGPL-2.1+).
"""
import pathlib
import re
import sys


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    root = pathlib.Path(sys.argv[1]) / "processing" / "openworld"
    gm = (root / "randomization" / "GiftModeProcessing.cs").read_text(encoding="utf-8-sig")
    gi = (root / "events" / "GiftDeliveryIntroEvent.cs").read_text(encoding="utf-8-sig")
    gifts = re.findall(r'possibleXmasGifts\["([^"]*)"\]\s*=\s*"([^"]*)";', gm)
    santa = re.search(r"SANTA_DIALOGUE_EVENTS\s*=\s*new int\[\]\s*\{([^}]*)\}", gi).group(1)
    santa = [int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]+", santa)]
    npcs = [int(x, 16) for x in re.findall(r'new NpcLocationData\("[^"]*",\s*"[^"]*",\s*(0x[0-9A-Fa-f]+)', gi)]
    out = ["/* Generated by tools/gen_p4_inject_gift.py from the upstream Moppu/SecretOfManaRandomizer v1.49 (LGPL-2.1).  Author: Moppleton. */",
           "struct gift_desc { const char *key, *text; };",
           "static const struct gift_desc POSSIBLE_XMAS_GIFTS[%d] = {" % len(gifts)]
    out += ['  {"%s", "%s"},' % g for g in gifts]
    out.append("};")
    out.append("static const int SANTA_DIALOGUE_EVENTS[%d] = {%s};" % (len(santa), ", ".join("0x%x" % x for x in santa)))
    out.append("static const int DELIVERY_EVENT_IDS[%d] = {%s};" % (len(npcs), ", ".join("0x%x" % x for x in npcs)))
    for var, first in (("hatNames", 1), ("armorNames", 22), ("accessoryNames", 43)):
        items = re.findall(var + r'\[(\d+)\]\s*=\s*"([^"]*)";', gm)
        ids = [int(i) for i, _ in items]
        assert ids == list(range(first, first + len(items))), var
        out.append("static const char *const %s[%d] = {" % (var.upper(), len(items)))
        out += ['  "%s",' % t for _, t in items]
        out.append("};")
    pathlib.Path(sys.argv[2]).write_text("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
