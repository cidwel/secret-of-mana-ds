#!/usr/bin/env python3
"""Generates src/sr_p4_sel_xmas_data.h from the upstream OpenWorldWinterTheme.cs / XmasMapPalettes.cs / giftbox_tiles.bin.

  gen_p4_xmas.py <upstream SoMRandomizer folder> <output .h>

Original tool of this repository (LGPL-2.1+).  The tables are derived from upstream code by Moppleton.
"""
import pathlib
import re
import sys


def read(p):
    return pathlib.Path(p).read_text(encoding="utf-8-sig")


def strip_comments(t):
    t = re.sub(r"/\*.*?\*/", "", t, flags=re.S)
    return re.sub(r"//[^\n]*", "", t)


def nums(s):
    return [int(x, 0) for x in re.findall(r"0x[0-9A-Fa-f]+|\d+", s)]


def main():
    src = pathlib.Path(sys.argv[1])
    wt = strip_comments(read(src / "processing/hacks/openworld/OpenWorldWinterTheme.cs"))
    xp = strip_comments(read(src / "processing/hacks/openworld/XmasMapPalettes.cs"))
    gift = (src / "Resources/giftbox_tiles.bin").read_bytes()
    o = ["/* Generated by tools/gen_p4_xmas.py from the upstream OpenWorldWinterTheme.cs, XmasMapPalettes.cs and giftbox_tiles.bin (Author: Moppleton).",
         " * LGPL-2.1 or later.  Do not edit. */", "#ifndef SR_P4_SEL_XMAS_DATA_H", "#define SR_P4_SEL_XMAS_DATA_H", "#include <stdint.h>", ""]

    # --- enemy colours and names (insertion order)
    ec = []
    for m in re.finditer(r"enemyColorChanges\[(\w+)\]\[(\w+)\] = new SnesColor\(([^)]*)\);", wt):
        e, p, rgb = int(m.group(1), 0), int(m.group(2), 0), [eval(x, {}, {}) for x in m.group(3).split(",")]
        ec.append((e, p) + tuple(rgb))
    o.append("struct sr_p4_xm_col { int16_t key, idx, r, g, b; };")
    o.append("static const struct sr_p4_xm_col sr_p4_xm_enemy_colors[] = {")
    o += ["  {%d, %d, %d, %d, %d}," % c for c in ec]
    o.append("};")
    names = re.findall(r"setName\(NamesOfThings\.INDEX_ENEMIES_START \+ (\w+), \"([^\"]*)\"\)", wt)
    o.append("struct sr_p4_xm_name { int16_t idx; const char *name; };")
    o.append("static const struct sr_p4_xm_name sr_p4_xm_enemy_names[] = {")
    o += ['  {%d, "%s"},' % (int(i, 0), n) for i, n in names]
    o.append("};")

    wm = []
    for m in re.finditer(r"worldMapReplacements\[(\w+)\]\[(\w+)\] = new SnesColor\(([^)]*)\);", wt):
        p, c, rgb = int(m.group(1), 0), int(m.group(2), 0), [eval(x, {}, {}) for x in m.group(3).split(",")]
        wm.append((p, c) + tuple(rgb))
    o.append("static const struct sr_p4_xm_col sr_p4_xm_world_colors[] = {")
    o += ["  {%d, %d, %d, %d, %d}," % c for c in wm]
    o.append("};")
    o.append("static const uint8_t sr_p4_xm_giftbox[%d] = {" % len(gift))
    for i in range(0, len(gift), 16):
        o.append("  " + ",".join("0x%02X" % b for b in gift[i:i + 16]) + ",")
    o.append("};")

    # --- XmasMapPalettes
    groups = [nums(m.group(2)) for m in re.finditer(r'groupedPalettes\.Add\("(\w+)", new byte\[\]\s*\{([^}]*)\}', xp)]
    # group members are listed before any comment text was stripped, so the numbers are exact
    o.append("static const uint8_t sr_p4_xm_group_len[%d] = {%s};" % (len(groups), ",".join(str(len(g)) for g in groups)))
    o.append("static const uint8_t sr_p4_xm_group[%d][2] = {%s};" % (len(groups), ",".join("{%d,%d}" % (g[0], g[1] if len(g) > 1 else 0) for g in groups)))
    assert all(len(g) <= 2 for g in groups)
    disp = [(int(a), int(b)) for a, b in re.findall(r"palSetToDispSetting\[(\d+)\] = (\d+);", xp)]
    o.append("static const uint8_t sr_p4_xm_disp[%d][2] = {%s};" % (len(disp), ",".join("{%d,%d}" % d for d in disp)))
    for name in ("dontChangePalettes", "dontDarkenPalettes", "darkenOnlyPalettes"):
        m = re.search(name + r" = new byte\[\]\s*\{([^}]*)\}", xp)
        v = nums(m.group(1))
        mask = [0] * 128
        for x in v:
            mask[x] = 1
        o.append("static const uint8_t sr_p4_xm_%s[128] = {%s};" % (name, ",".join(map(str, mask))))

    def table(var, prefix):
        # <var>[N] = palNN...; and palNN...[k] = new int[] {...}.ToList();
        lists = {}
        for m in re.finditer(r"(\w+)\[(\d+)\] = new int\[\] \{([^}]*)\}\.ToList\(\);", xp):
            lists.setdefault(m.group(1), []).append((int(m.group(2)), nums(m.group(3))))
        res = {}
        order = {}
        for m in re.finditer(var + r"\[(\d+)\] = (\w+);", xp):
            pal = int(m.group(1))
            d = {}
            ordl = []
            for k, v in lists[m.group(2)]:
                if k not in d:
                    ordl.append(k)
                d[k] = v
            res[pal] = d
            order[pal] = ordl
        masks = [[0] * 8 for _ in range(128)]
        first = [0] * 128
        for pal, d in res.items():
            for k, v in d.items():
                mk = 0
                for c in v:
                    mk |= 1 << c
                masks[pal][k] = mk
            first[pal] = sum(1 << c for c in d[order[pal][0]])
        o.append("static const uint16_t sr_p4_xm_%s[128][8] = {" % prefix)
        o.extend(["  {%s}," % ",".join(str(x) for x in r) for r in masks])
        o.append("};")
        if prefix == "exc":
            o.append("static const uint16_t sr_p4_xm_exc_first[128] = {%s};" % ",".join(str(x) for x in first))

    table("grayscaleColors", "gray")
    table("paletteExceptions", "exc")
    o.append("#endif")
    pathlib.Path(sys.argv[2]).write_text("\n".join(o) + "\n")


main()
