#!/usr/bin/env python3
"""Generates src/sr_p3_cave_pat.h (the TileReplacer patterns of CaveTileEdges.cs) from the upstream C# source.
usage: gen_p3_cave.py CaveTileEdges.cs > src/sr_p3_cave_pat.h"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8-sig").read()
head, second = src.split("// second pass")
CALL = re.compile(r"TileReplacer\.applyPattern\(new TileReplacer\.ReplacementPattern\(")


def parse_call(text, pos):
    """Returns (arrays, width, altname, endpos) of the call whose argument list starts at pos."""
    arrays = []
    i = pos
    while True:
        m = re.compile(r"\s*new string\[\]\s*\{").match(text, i)
        if not m:
            break
        i = m.end()
        items = []
        while text[i] != "}":
            if text[i] == '"':
                j = text.index('"', i + 1)
                items.append(text[i + 1:j])
                i = j + 1
            else:
                i += 1
        i += 1
        arrays.append(items)
        m2 = re.compile(r"\s*,").match(text, i)
        if m2:
            i = m2.end()
    m = re.compile(r"\s*(\d+)\)\s*,\s*layer1Copy,\s*layer1,\s*(\w+),\s*rect\);").match(text, i)
    assert m, text[i:i + 80]
    return arrays, int(m.group(1)), m.group(2), m.end()


def emit(text, tag, out):
    pos = 0
    n = 0
    entries = []
    while True:
        m = CALL.search(text, pos)
        if not m:
            break
        arrays, width, alt, pos = parse_call(text, m.end())
        assert len(arrays) in (2, 3)
        search, inject = arrays[0], arrays[1]
        altinj = arrays[2] if len(arrays) == 3 else None
        assert len(search) == len(inject) and (altinj is None or len(altinj) == len(search))
        for nm, a in (("s", search), ("i", inject), ("a", altinj)):
            if a is None:
                continue
            out.append("static const char *const cave_%s%d_%s[] = {%s};" % (tag, n, nm, ", ".join('"%s"' % x for x in a)))
        entries.append("  {{cave_%s%d_s, cave_%s%d_i, %s, %d, %d}, %d}," % (tag, n, tag, n, ("cave_%s%d_a" % (tag, n)) if altinj else "NULL", width, len(search), 1 if alt == "layer2" else 0))
        n += 1
    out.append("static const struct cave_pat cave_pats_%s[] = {" % tag)
    out.extend(entries)
    out.append("};")
    out.append("#define CAVE_NPATS_%s %d" % (tag.upper(), n))


out = ["/* Generated by tools/gen_p3_cave.py from CaveTileEdges.cs (Author: Moppleton). Do not edit. */",
       "struct cave_pat {", "  struct ac_pattern p;", "  int use_alt;   /* the C# passes layer2 (1) or null (0) as the alternate layer */", "};"]
emit(head, "a", out)
emit(second, "b", out)
print("\n".join(out))
