#!/usr/bin/env python3
"""Generates src/sr_rom_recipes.c: how to rebuild the upstream embedded resources that are partly vanilla ROM data.

  gen_rom_recipes.py <upstream SoMRandomizer folder> <vanilla US v1.0 ROM> <output .c>

The upstream resources listed below (Vineshroom tiles, Ancient Cave and boss rush map palette sets, two Ancient Cave custom maps) were made by
editing dumps of the game's own data, so large parts of them are byte-identical to the ROM.  This repository and the binaries built from it must not
carry ROM bytes.  For every resource the tool splits the bytes into runs that exist in the ROM (stored as a ROM offset and a length only) and the
remaining bytes (the author's edits, stored as literals), plus the CRC-32 of the whole resource.  At generation time sr_rom_res() (src/sr_rom_res.c)
rebuilds the resource from the user's own ROM and refuses a ROM whose bytes do not give the same CRC.
A ROM run is copied from the ROM only when it is at least MINRUN bytes long and has at least MIN_DISTINCT different values; everything shorter stays
a literal, so no literal run holds 32 or more consecutive ROM bytes.
Needs the ROM and the upstream checkout; the output is committed.  Original tool of this repository (LGPL-2.1+).
"""
import pathlib
import sys
import zlib

MINRUN = 12
MIN_DISTINCT = 4

RESOURCES = [("vineshroom_tiles.bin", "Resources/vineshroom_tiles.bin")]
for d, names in (("accave", ("fierycave", "graycave", "undinecave")), ("acforest", ("fall", "night", "spring", "sunset", "winter")),
                 ("acisland", ("alt", "greenwater", "night")), ("acruins", ("darkruins", "nightruins"))):
    for n in names:
        RESOURCES.append(("%s.%s.bin" % (d, n), "Resources/mapPalettes/%s/%s.bin" % (d, n)))
RESOURCES += [("acManafortBossArenaL1.bin", "Resources/customMaps/acManafortBossArenaL1.bin"),
              ("acManafortNpcRoomL1.bin", "Resources/customMaps/acManafortNpcRoomL1.bin"),
              ("bossRushRestMapPal.bin", "Resources/mapPalettes/bossrush/bossRushRestMapPal.bin")]
LIT = 0xFFFFFFFF


def split(data, rom):
    segs = []
    lit = bytearray()
    i = 0
    while i < len(data):
        best = (0, 0)
        if len(data) - i >= MINRUN:
            key = data[i:i + MINRUN]
            at = rom.find(key)
            while at >= 0:
                n = MINRUN
                while i + n < len(data) and at + n < len(rom) and data[i + n] == rom[at + n]:
                    n += 1
                if n > best[0]:
                    best = (n, at)
                at = rom.find(key, at + 1)
        if best[0] >= MINRUN and len(set(data[i:i + best[0]])) >= MIN_DISTINCT:
            segs.append((best[1], best[0]))
            i += best[0]
        else:
            if segs and segs[-1][0] == LIT:
                segs[-1] = (LIT, segs[-1][1] + 1)
            else:
                segs.append((LIT, 1))
            lit.append(data[i])
            i += 1
    return segs, bytes(lit)


def rebuild(segs, lit, rom):
    out = bytearray()
    p = 0
    for off, n in segs:
        if off == LIT:
            out += lit[p:p + n]
            p += n
        else:
            out += rom[off:off + n]
    return bytes(out)


def main():
    if len(sys.argv) != 4:
        print(__doc__)
        return 2
    src = pathlib.Path(sys.argv[1])
    rom = pathlib.Path(sys.argv[2]).read_bytes()
    if len(rom) == 0x200000 + 0x200:
        rom = rom[0x200:]
    if len(rom) != 0x200000 or rom[0xFFC0:0xFFCE] != b"Secret of MANA" or rom[0xFFD9] != 1 or rom[0xFFDB] != 0:
        raise SystemExit("not the US v1.0 ROM")
    out = ['/* Generated by tools/gen_rom_recipes.py: how to rebuild the upstream resources that are partly vanilla ROM data, from the user\'s ROM.',
           ' * Holds ROM offsets and lengths plus the author\'s own edited bytes; no run of ROM data.  Do not edit by hand.  LGPL-2.1 or later. */',
           '#include "sr_core.h"', '']
    rows = []
    total_lit = total_rom = 0
    for k, (name, rel) in enumerate(RESOURCES):
        data = (src / rel).read_bytes()
        segs, lit = split(data, rom)
        assert rebuild(segs, lit, rom) == data
        total_lit += len(lit)
        total_rom += len(data) - len(lit)
        out.append("static const struct sr_rom_seg seg_%d[] = {" % k)
        for j in range(0, len(segs), 6):
            out.append("  " + " ".join("{0x%XU,%d}," % s for s in segs[j:j + 6]))
        out.append("};")
        if lit:
            out.append("static const uint8_t lit_%d[%d] = {" % (k, len(lit)))
            for j in range(0, len(lit), 24):
                out.append("  " + ",".join("0x%02X" % b for b in lit[j:j + 24]) + ",")
            out.append("};")
        rows.append('  {"%s", %d, 0x%08XU, seg_%d, %d, %s},' % (name, len(data), zlib.crc32(data), k, len(segs), "lit_%d" % k if lit else "NULL"))
        out.append("")
    out.append("const struct sr_rom_recipe sr_rom_recipes[] = {")
    out += rows
    out.append("};")
    out.append("const int sr_rom_recipe_count = %d;" % len(RESOURCES))
    pathlib.Path(sys.argv[3]).write_text("\n".join(out) + "\n")
    print("%d resources, %d bytes taken from the ROM at run time, %d literal bytes" % (len(RESOURCES), total_rom, total_lit))
    return 0


if __name__ == "__main__":
    sys.exit(main())
