#!/usr/bin/env python3
"""Generates src/sr_p3_ac_diff.c from Resources/difficulty_{casual,hard,reallyhard}.properties of the upstream project (Ancient Cave presets).

usage: gen_p3_diff.py UPSTREAM_SoMRandomizer_DIR OUT.c
The row set and order are those of the boss rush table (sr_w8_diff_rows); a key missing from a file would read as 1.0 in the C# reader.
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
KEYS = []
txt = open(__file__.rsplit("/tools/", 1)[0] + "/src/sr_p2_bossrush_data.c", encoding="utf-8").read()
for m in re.finditer(r'\{"(\w+)", \{', txt[txt.index("sr_w8_diff_rows[]"):]):
    KEYS.append(m.group(1))


def read(name):
    props = {}
    for line in open("%s/Resources/difficulty_%s.properties" % (src, name), encoding="utf-8-sig").read().splitlines():
        line = line.strip()
        if line.startswith("#"):
            continue
        i = line.find("=")
        if i > 0:
            k, v = line[:i].strip(), line[i + 1:].strip()
            if k and v:
                props[k] = v
    return props


def num(p, key):
    try:
        return float(p[key])
    except (KeyError, ValueError):
        return 1.0


tables = [read(n) for n in ("casual", "hard", "reallyhard")]


def fmt(v):
    return repr(v)


with open(out, "w", encoding="utf-8") as f:
    f.write("""/* libsomrando: C port of Moppu/SecretOfManaRandomizer v1.49 (commit 1404b7b).  LGPL-2.1 or later, see sr_core.h and COPYING.LIB.
 *
 * Ancient Cave: difficulty presets taken from Resources/difficulty_{casual,hard,reallyhard}.properties (Author: Moppleton).
 * Generated by tools/gen_p3_diff.py, 2026-10-18.
 */
#include "sr_p2_bossrush_data.h"

const struct sr_w8_diff_row sr_p3_ac_diff_rows[] = {
""")
    for k in KEYS:
        f.write('  {"%s", {%s, %s, %s}},\n' % ((k,) + tuple(fmt(num(t, k)) for t in tables)))
    f.write("};\nconst int sr_p3_ac_diff_row_count = %d;\n" % len(KEYS))
