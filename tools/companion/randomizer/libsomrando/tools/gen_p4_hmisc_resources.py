#!/usr/bin/env python3
"""Turns the upstream nesoberi images into a C file, outside the repository.

  gen_p4_hmisc_resources.py <upstream SoMRandomizer folder> <output .c>

The 68 bmp files of Resources/nesoberi are third-party fan art; they are generated at build time from a checkout of
Moppu/SecretOfManaRandomizer instead of being stored in this repository.  For every image only the 16x24 area read by Nesoberi.cs through
Bitmap.GetPixel is emitted (decoded exactly like util/img/Bitmap.cs: 24 bpp, bottom-up).  The character table (names, birthdays, outfit order) is
read from Nesoberi.cs so that the random picks index the same entries.  Original tool of this repository (LGPL-2.1+).
"""
import pathlib
import re
import struct
import sys


def decode(data, name):
    """util/img/Bitmap.cs constructor + GetPixel(x, y) for x < 16, y < 24; returns R,G,B bytes row by row."""
    if data[0:2] != b"BM":
        raise ValueError(name + ": not a bmp")
    image_ptr = struct.unpack_from("<I", data, 10)[0]
    dib_len = struct.unpack_from("<I", data, 14)[0]
    if dib_len < 12:
        raise ValueError(name + ": bad DIB")
    if dib_len > 12:
        compression = struct.unpack_from("<I", data, 14 + 12 + 4)[0]
        if compression != 0:
            raise ValueError(name + ": compressed")
        w, h = struct.unpack_from("<II", data, 14 + 4)
        bpp = struct.unpack_from("<H", data, 14 + 12 + 2)[0]
    else:
        w, h, bpp = struct.unpack_from("<HHH", data, 14 + 4)[0], struct.unpack_from("<H", data, 14 + 6)[0], struct.unpack_from("<H", data, 14 + 10)[0]
    if bpp != 24 or w < 16 or h < 24:
        raise ValueError("%s: unexpected %dx%d %dbpp" % (name, w, h, bpp))
    stride = (bpp * w + 31) // 32 * 4
    pix = data[image_ptr:image_ptr + h * stride]
    if len(pix) != h * stride:
        raise ValueError(name + ": short pixel data")
    out = bytearray()
    for y in range(24):
        for x in range(16):
            off = (h - y - 1) * stride + x * bpp // 8
            out += bytes((pix[off + 2], pix[off + 1], pix[off + 0]))
    return bytes(out)


def parse_table(text):
    chars = []
    cur = None
    for line in text.split("\n"):
        if "new NesoCharInfo(new IndividualNeso[]" in line:
            cur = []
            continue
        m = re.search(r'new IndividualNeso\("([^"]+)",\s*"([^"]*)"\)', line)
        if m and cur is not None:
            cur.append(m.group(1))
            continue
        m = re.match(r'\s*\}, "([^"]+)", (\d+), (\d+)\)\);', line)
        if m and cur is not None:
            chars.append((m.group(1), int(m.group(2)), int(m.group(3)), cur))
            cur = None
    return chars


def carr(b):
    return "\n".join("  " + ",".join("0x%02X" % v for v in b[i:i + 24]) + "," for i in range(0, len(b), 24))


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    src = pathlib.Path(sys.argv[1])
    chars = parse_table((src / "processing/hacks/openworld/Nesoberi.cs").read_text(encoding="utf-8-sig"))
    files, outfit_image, rows = [], [], []
    for name, month, day, outs in chars:
        rows.append((name, month, day, len(outfit_image), len(outs)))
        for f in outs:
            if f not in files:
                files.append(f)
            outfit_image.append(files.index(f))
    out = ['/* Generated by gen_p4_hmisc_resources.py from the upstream Moppu/SecretOfManaRandomizer v1.49 resources.  Do not edit, do not commit. */',
           '#include "sr_p4_hk_neso.h"', ""]
    out.append("static const struct sr_p4_neso_char chars[] = {")
    for name, month, day, first, n in rows:
        out.append('  {"%s", %d, %d, %d, %d},' % (name, month, day, first, n))
    out.append("};")
    out.append("static const uint16_t outfit_image[] = {" + ",".join(str(i) for i in outfit_image) + "};")
    out.append("static const uint8_t images[%d][SR_P4_NESO_IMG_BYTES] = {" % len(files))
    for f in files:
        out.append("{ /* %s */" % f)
        out.append(carr(decode((src / "Resources/nesoberi" / f).read_bytes(), f)))
        out.append("},")
    out.append("};")
    out.append("static const uint8_t snow[SR_P4_NESO_IMG_BYTES] = {")
    out.append(carr(decode((src / "Resources/nesoberi/snow_neso.bmp").read_bytes(), "snow_neso.bmp")))
    out.append("};")
    out.append("const struct sr_p4_neso_data sr_p4_neso_data = {%d, chars, %d, outfit_image, images, snow};" % (len(rows), len(outfit_image)))
    pathlib.Path(sys.argv[2]).write_text("\n".join(out) + "\n")
    print("%d characters, %d outfits, %d images" % (len(rows), len(outfit_image), len(files)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
