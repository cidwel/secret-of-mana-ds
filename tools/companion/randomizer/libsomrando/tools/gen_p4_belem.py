#!/usr/bin/env python3
"""Generates src/sr_p4_belem_code.h: the emit blocks of BossElementRando.cs (spell lists, spell-pick subroutines, patch code).

  gen_p4_belem.py <upstream SoMRandomizer folder> <code.h> <data.h>

Original tool of this repository (LGPL-2.1+).
"""
import re
import sys

src = open(sys.argv[1] + "/processing/hacks/openworld/BossElementRando.cs", encoding="utf-8-sig").read().split("\n")
start = next(i for i, l in enumerate(src) if "// spell + targetting combos" in l)
end = next(i for i, l in enumerate(src) if "// for palette shifts, take average hue" in l)
out = ["/* Generated by tools/gen_p4_belem.py from processing/hacks/openworld/BossElementRando.cs (Author: Moppleton). Do not edit. */"]
incom = False
for l in src[start:end]:
    s = l.strip()
    if incom:
        out.append('   ' + s)
        incom = '*/' not in s
        continue
    if s.startswith('/*') and '*/' not in s:
        incom = True
        out.append('  ' + s)
        continue
    if not s:
        out.append("")
        continue
    s = s.replace("context.workingOffset", "c->working_offset").replace("(byte)", "(uint8_t)")
    m = re.match(r"outRom\[c->working_offset\+\+\] = (.*?);(\s*//.*)?$", s)
    if m:
        out.append("  E(%s);%s" % (m.group(1), m.group(2) or ""))
        continue
    m = re.match(r"outRom\[(0x[0-9A-Fa-f]+)\] = (.*?);$", s)
    if m:
        out.append("  P(%s, %s);" % (m.group(1), m.group(2)))
        continue
    m = re.match(r"int\[\] (\w+) = new int\[\] (\{.*\});$", s)
    if m:
        out.append("  int %s[] = %s;" % (m.group(1), m.group(2)))
        continue
    m = re.match(r"int\[\] (\w+) = new int\[(\d+)\];$", s)
    if m:
        out.append("  int %s[%s];" % (m.group(1), m.group(2)))
        continue
    if re.match(r"(int \w+ = [^;]*;|for ?\(.*\)|\{|\}|//.*|/\*.*|\*.*|elementValue <<= 1;|subrLocations\[i\] = [^;]*;)(\s*//.*)?$", s):
        out.append("  " + s if not s.startswith("*") else "  " + s)
        continue
    sys.exit("unhandled line: " + l)
open(sys.argv[2], "w").write("\n".join(out) + "\n")

# ---- data tables
vals = open(sys.argv[1] + "/processing/common/SomVanillaValues.cs", encoding="utf-8-sig").read()
bossid = {m.group(1): int(m.group(2)) for m in re.finditer(r"const byte (BOSSID_\w+) = (\d+);", vals)}
text = "\n".join(src)


def block(name):
    i = text.index(name)
    j = text.index("};", i)
    body = text[text.index("{", i):j]
    body = re.sub(r"//[^\n]*", "", body)
    return body


def entries(name, valpat):
    body = block(name)
    return [(bossid[m.group(1)], m.group(2)) for m in re.finditer(r"\{\s*(BOSSID_\w+)\s*,\s*(" + valpat + r")\s*\}", body, re.S)]


po = [(b, [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", v)]) for b, v in entries("Dictionary<int, List<int>> paletteOffsets", r"new int\[\] \{.*?\}\.ToList\(\)")]
hue = entries("Dictionary<int, int> bossBaseHue", r"\d+")
sat = entries("Dictionary<int, double> bossSatMultiplier", r"[\d.]+ */ *255\.0")
flat = entries("Dictionary<int, double> hueFlatten", r"[\d.]+")
dont = [(b, [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", v)]) for b, v in entries("Dictionary<int, List<byte>> dontUseElements", r"new byte\[\] \{.*?\}\.ToList\(\)")]
o = ["/* Generated by tools/gen_p4_belem.py from BossElementRando.cs (Author: Moppleton). Do not edit. Insertion order of the C# dictionaries. */",
     "struct sr_p4_belem_pal { int boss, n, off[9]; };", "struct sr_p4_belem_dont { int boss, n; uint8_t ele[3]; };",
     "static const struct sr_p4_belem_pal belem_pal[] = {"]
for b, l in po:
    o.append("  {%d, %d, {%s}}," % (b, len(l), ", ".join("0x%02X" % x for x in l)))
o.append("};")
o.append("static const struct { int boss, hue; } belem_hue[] = {")
o += ["  {%d, %s}," % (b, v) for b, v in hue]
o.append("};")
o.append("static const struct { int boss; double mul; } belem_sat[] = {")
o += ["  {%d, %s}," % (b, v) for b, v in sat]
o.append("};")
o.append("static const struct { int boss; double flat; } belem_flat[] = {")
o += ["  {%d, %s}," % (b, v) for b, v in flat]
o.append("};")
o.append("static const struct sr_p4_belem_dont belem_dont[] = {")
for b, l in dont:
    o.append("  {%d, %d, {%s}}," % (b, len(l), ", ".join("0x%02X" % x for x in l)))
o.append("};")
open(sys.argv[3], "w").write("\n".join(o) + "\n")
