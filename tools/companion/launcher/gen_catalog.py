#!/usr/bin/env python3
"""Generate som_launcher_catalog.c from tools/companion/randomizer/presets.json (run after presets_tool.py build).

  gen_catalog.py            rewrite som_launcher_catalog.c
  gen_catalog.py --check    exit 1 when the committed file is out of date
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE.parent / 'randomizer' / 'presets.json'
OUT = HERE / 'som_launcher_catalog.c'


def cs(s):
    return json.dumps(s, ensure_ascii=True)


def fixed(v, dec):
    return int(round(float(v) * 10 ** dec))


class Gen:
    def __init__(self):
        self.lines = []
        self.n = 0

    def emit(self, s=''):
        self.lines.append(s)

    def option_array(self, name, opts, export=False):
        for i, o in enumerate(opts):
            p = '%s_%d' % (name, i)
            vals = o.get('values') or []
            if o['type'] == 'bool':
                vals = [dict(v='no', l='No'), dict(v='yes', l='Yes')]
            if vals:
                self.emit('static const struct sl_value %s_v[] = {' % p)
                for v in vals:
                    self.emit('  {%s, %s, %s},' % (cs(v['v']), cs(v['l']), cs(v.get('full', ''))))
                self.emit('};')
            if o.get('rand_pool'):
                self.emit('static const char *const %s_p[] = {%s};' % (p, ', '.join(cs(x) for x in o['rand_pool'])))
            if o.get('requires'):
                self.emit('static const struct sl_req %s_r[] = {%s};' % (p, ', '.join(
                    '{%s, %s}' % (cs(k), cs('|' + '|'.join(v) + '|')) for k, v in o['requires'].items())))
        self.emit('%sconst struct sl_option %s[] = {' % ('' if export else 'static ', name))
        for i, o in enumerate(opts):
            p = '%s_%d' % (name, i)
            t = o['type']
            vals = o.get('values') or []
            if t == 'bool':
                dflt, nv = (1 if o['default'] == 'yes' else 0), 2
            elif t == 'enum':
                dflt, nv = [v['v'] for v in vals].index(o['default']), len(vals)
            elif t == 'multi':
                names = [v['v'] for v in vals]
                dflt, nv = sum(1 << names.index(x) for x in o['default'].split(',') if x), len(vals)
            elif t == 'num':
                dflt, nv = fixed(o['default'], o['decimals']), 0
            else:
                raise SystemExit('unsupported option type %s (%s)' % (t, o['key']))
            tcode = {'bool': 'SL_O_BOOL', 'enum': 'SL_O_ENUM', 'num': 'SL_O_NUM', 'multi': 'SL_O_MULTI'}[t]
            dec = o.get('decimals', 0)
            mn = fixed(o['min'], dec) if t == 'num' else 0
            mx = fixed(o['max'], dec) if t == 'num' else 0
            st = fixed(o['step'], dec) if t == 'num' else 0
            pool = o.get('rand_pool')
            req = o.get('requires')
            self.emit('  {%s, %s, %s, %s, %s, %d, %d, %d, %d, %s, %d, %d, %d, %d, %d, %s, %d, %s},' % (
                cs(o['key']), cs(o['label']), cs(o['group']), cs(o.get('help', '')), tcode, int(o['advanced']), int(o['randomize']), dec,
                nv, (p + '_v') if (vals or t == 'bool') else 'NULL', dflt, mn, mx, st,
                len(pool) if pool else 0, (p + '_p') if pool else 'NULL', len(req) if req else 0, (p + '_r') if req else 'NULL'))
        self.emit('};')
        self.emit()


def main():
    cat = json.loads(SRC.read_text())
    g = Gen()
    g.emit('/* GENERATED by tools/companion/launcher/gen_catalog.py from tools/companion/randomizer/presets.json.  Do not edit. */')
    g.emit('/* Option names and values: Moppu/SecretOfManaRandomizer v1.49, LGPL-2.1. */')
    g.emit('#include "som_launcher_catalog.h"')
    g.emit()
    g.emit('const char sl_generator_version[] = %s;' % cs(cat['generator']['version']))
    g.emit('const char sl_generator_commit[] = %s;' % cs(cat['generator']['commit']))
    g.emit()
    g.option_array('sl_common', cat['common_options'], export=True)
    mode_names = list(cat['modes'])
    for m in mode_names:
        e = cat['modes'][m]
        g.option_array('sl_opts_' + m, e['options'])
        if e['difficulty']:
            g.emit('static const char *const sl_diff_%s[] = {%s};' % (m, ', '.join(cs(x) for x in e['difficulty']['values'])))
        cons = e['constraints']
        if cons:
            g.emit('static const struct sl_cons sl_cons_%s[] = {' % m)
            for c in cons:
                if 'any' in c:
                    g.emit('  {SL_C_ANY, %d, {%s}},' % (len(c['any']), ', '.join(cs(k) for k in c['any'])))
                else:
                    g.emit('  {SL_C_LE, 2, {%s}},' % ', '.join(cs(k) for k in c['le']))
            g.emit('};')
    g.emit('const int sl_ncommon = %d;' % len(cat['common_options']))
    g.emit('const int sl_nmodes = %d;' % len(mode_names))
    g.emit('const struct sl_mode sl_modes[] = {')
    for m in mode_names:
        e = cat['modes'][m]
        d = e['difficulty']
        g.emit('  {%s, %s, %s, %d, sl_opts_%s, %d, %s, %d, %d, %s},' % (
            cs(m), cs(e['name']), cs(e['description']), len(e['options']), m,
            len(d['values']) if d else 0, ('sl_diff_' + m) if d else 'NULL', d['values'].index(d['default']) if d else 0,
            len(e['constraints']), ('sl_cons_' + m) if e['constraints'] else 'NULL'))
    g.emit('};')
    g.emit('const int sl_npresets = %d;' % len(cat['presets']))
    for i, p in enumerate(cat['presets']):
        g.emit('static const struct sl_set sl_pset_%d[] = {%s};' % (i, ', '.join('{%s, %s}' % (cs(k), cs(v)) for k, v in p['set'].items()) or '{0, 0}'))
    g.emit('const struct sl_preset sl_presets[] = {')
    for i, p in enumerate(cat['presets']):
        mi = mode_names.index(p['mode'])
        di = cat['modes'][p['mode']]['difficulty']['values'].index(p['difficulty']) if p.get('difficulty') else -1
        g.emit('  {%s, %s, %s, %d, %d, %d, sl_pset_%d},' % (cs(p['id']), cs(p['name']), cs(p['description']), mi, di, len(p['set']), i))
    g.emit('};')
    text = '\n'.join(g.lines) + '\n'
    if '--check' in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print('wrote %s (%d lines)' % (OUT, text.count('\n')))


main()
