#!/usr/bin/env python3
"""Generates src/sr_p3_manafort_rooms_data.h from the Manafort interior room makers of the upstream project.

  gen_p3_manafort.py <upstream SoMRandomizer folder> <output .h>

Reads the static byte[] tables of processing/ancientcave/mapgen/manafortint/rooms (Author: Moppleton).
Original tool of this repository (LGPL-2.1+).
"""
import pathlib
import re
import sys

ROOMS = ["BridgeRoom", "CircleLineRoom", "CrystalRoom", "DiagonalRoom", "MultiDiagonalRoom", "StartEndRoom"]


def tables(text):
    out = []
    for m in re.finditer(r"static byte\[\]\s+(\w+)\s*=\s*new byte\[\]\s*\{(.*?)\};", text, re.S):
        body = re.sub(r"//[^\n]*", "", m.group(2))
        out.append((m.group(1), [int(v) for v in re.findall(r"\d+", body)]))
    return out


def main():
    src = pathlib.Path(sys.argv[1]) / "processing/ancientcave/mapgen/manafortint/rooms"
    lines = ["/* GENERATED by tools/gen_p3_manafort.py from processing/ancientcave/mapgen/manafortint/rooms (Author: Moppleton).  Do not edit.",
             " * LGPL-2.1 or later. */", "#ifndef SR_P3_MANAFORT_ROOMS_DATA_H", "#define SR_P3_MANAFORT_ROOMS_DATA_H", ""]
    for room in ROOMS:
        for name, vals in tables((src / (room + ".cs")).read_text(encoding="utf-8-sig")):
            lines.append("static const uint8_t mf_%s_%s[%d] = {" % (room, name, len(vals)))
            for i in range(0, len(vals), 20):
                lines.append("  " + ",".join(str(v) for v in vals[i:i + 20]) + ",")
            lines.append("};")
    lines += ["", "#endif", ""]
    pathlib.Path(sys.argv[2]).write_text("\n".join(lines))


main()
