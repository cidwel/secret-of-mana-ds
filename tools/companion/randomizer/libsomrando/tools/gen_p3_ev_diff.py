#!/usr/bin/env python3
"""Generates src/sr_p3_ev_diff.c: the Ancient Cave difficulty rows from Resources/difficulty_{casual,hard,reallyhard}.properties.

usage: gen_p3_ev_diff.py UPSTREAM_RESOURCES_DIR OUT.c
Same keys and order as the boss rush table (DifficultySettings.readFromResourceFile: a missing or unparsable value becomes 1.0).
Part of libsomrando, LGPL-2.1 or later.
"""
import os
import sys

GROWTH = ["enemyLevel", "enemyStr", "enemyAgi", "enemyInt", "enemyWis", "enemyEvade", "enemyMevade", "enemyHp", "enemyMp", "enemyDef",
          "enemyMdef", "enemyExp", "enemyGold", "enemyWeaponLev", "enemyMagicLev", "enemyWeaponDamage", "manaPower"]
PLAIN = ["tonpoleMp", "bossStatMultiplier", "bossExpMultiplier", "bossGoldMultiplier", "bossHpMultiplier", "startingGold",
         "startingConsumables", "restoreCost", "numPhannas", "numElements", "numWatts", "continueCost", "startingLevel", "restoresLimit"]
# row order of the boss rush table (sr_p2_bossrush_data.c): tonpoleMp sits after enemyMp, the boss multipliers after manaPower
ORDER = []
for g in GROWTH:
    ORDER += [g + "_base", g + "_growth", g + "_exp"]
    if g == "enemyMp":
        ORDER.append("tonpoleMp")
ORDER += [k for k in PLAIN if k != "tonpoleMp"]


def read(path):
    props = {}
    with open(path, encoding="utf-8-sig") as f:
        for line in f:
            line = line.strip()
            if "=" in line and not line.startswith("#"):
                k, v = line.split("=", 1)
                props[k.strip()] = v.strip()
    return props


def value(props, key):
    try:
        return float(props[key])
    except (KeyError, ValueError):
        return 1.0


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    cols = [read(os.path.join(sys.argv[1], "difficulty_%s.properties" % d)) for d in ("casual", "hard", "reallyhard")]
    with open(sys.argv[2], "w") as f:
        f.write("/* Generated by tools/gen_p3_ev_diff.py from Resources/difficulty_{casual,hard,reallyhard}.properties.  LGPL-2.1 or later. */\n")
        f.write('#include "sr_p2_bossrush_data.h"\n\n')
        f.write("const struct sr_w8_diff_row sr_p3_ev_diff_rows[] = {\n")
        for k in ORDER:
            f.write('  {"%s", {%s}},\n' % (k, ", ".join(repr(value(p, k)) for p in cols)))
        f.write("};\nconst int sr_p3_ev_diff_row_count = %d;\n" % len(ORDER))


if __name__ == "__main__":
    main()
