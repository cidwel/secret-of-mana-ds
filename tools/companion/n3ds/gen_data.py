#!/usr/bin/env python3
"""Writes build/gen_data.h from data/credits.json and tools/gameplay/gameplay_menu.json (the single sources of the credits text and of
the gameplay option list); the 3DS app has no JSON parser at run time.  Usage: gen_data.py OUT.h [credits.json gameplay_menu.json]"""
import json, pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]


def c(s):
    s = '' if s is None else str(s)
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def main():
    out = pathlib.Path(sys.argv[1])
    credits = json.loads(pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else ROOT / 'data' / 'credits.json').read_text())
    menu = json.loads(pathlib.Path(sys.argv[3] if len(sys.argv) > 3 else ROOT / 'tools' / 'gameplay' / 'gameplay_menu.json').read_text())
    L = ['/* generated by tools/companion/n3ds/gen_data.py; do not edit */', '#ifndef SOM_N3DS_GEN_DATA_H', '#define SOM_N3DS_GEN_DATA_H', '']
    L.append('struct gd_credit { const char *who, *what, *patch, *license, *url; };')
    L.append('struct gd_value { const char *v, *l; };')
    L.append('struct gd_opt { const char *key, *label, *group, *help, *def; int type, advanced, nvals, min, max; const struct gd_value *vals; };   /* type: 0 enum, 1 num, 2 bool */')
    L.append('struct gd_preset { const char *id, *name, *desc; int n; const char *const *keys; const char *const *vals; };')
    L.append('')
    L.append('static const char GD_CREDITS_TITLE[] = %s;' % c(credits.get('title', 'Special thanks')))
    L.append('static const struct gd_credit GD_CREDITS[] = {')
    for e in credits['entries']:
        L.append('  {%s, %s, %s, %s, %s},' % (c(e.get('who')), c(e.get('what')), c(e.get('patch', e.get('name', ''))), c(e.get('license', '')), c(e.get('url', ''))))
    L.append('};')
    L.append('#define GD_NCREDITS %d' % len(credits['entries']))
    L.append('')
    for i, o in enumerate(menu['options']):
        if o['type'] == 'enum':
            L.append('static const struct gd_value GD_VALS_%d[] = {%s};' % (i, ', '.join('{%s, %s}' % (c(v['v']), c(v['l'])) for v in o['values'])))
    L.append('static const struct gd_opt GD_OPTS[] = {')
    for i, o in enumerate(menu['options']):
        t = {'enum': 0, 'num': 1, 'bool': 2}[o['type']]
        L.append('  {%s, %s, %s, %s, %s, %d, %d, %d, %d, %d, %s},' % (
            c(o['key']), c(o['label']), c(o['group']), c(o.get('help', '')), c(o.get('default', '')), t, 1 if o.get('advanced') else 0,
            len(o.get('values', [])), o.get('min', 0), o.get('max', 0), 'GD_VALS_%d' % i if t == 0 else 'NULL'))
    L.append('};')
    L.append('#define GD_NOPTS %d' % len(menu['options']))
    L.append('static const char *const GD_GROUPS[] = {%s};' % ', '.join(c(g) for g in menu['groups']))
    L.append('#define GD_NGROUPS %d' % len(menu['groups']))
    for i, p in enumerate(menu.get('presets', [])):
        ks, vs = list(p['set'].keys()), [str(v) for v in p['set'].values()]
        L.append('static const char *const GD_PK_%d[] = {%s};' % (i, ', '.join(c(k) for k in ks) or 'NULL'))
        L.append('static const char *const GD_PV_%d[] = {%s};' % (i, ', '.join(c(v) for v in vs) or 'NULL'))
    L.append('static const struct gd_preset GD_PRESETS[] = {')
    for i, p in enumerate(menu.get('presets', [])):
        L.append('  {%s, %s, %s, %d, GD_PK_%d, GD_PV_%d},' % (c(p['id']), c(p['name']), c(p['description']), len(p['set']), i, i))
    L.append('};')
    L.append('#define GD_NPRESETS %d' % len(menu.get('presets', [])))
    L.append('')
    L.append('#endif')
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(L) + '\n')


main()
