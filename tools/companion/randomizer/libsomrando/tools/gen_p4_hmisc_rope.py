#!/usr/bin/env python3
"""Emits the magic rope door table of MagicRopeRefactor.cs as a C header (generated data, committed).

  gen_p4_hmisc_rope.py <upstream SoMRandomizer folder> <out .h>

The C# fills a Dictionary<int,int> map -> door in source order (a later assignment replaces an earlier one) and then writes 512 entries.
Original tool of this repository (LGPL-2.1+).
"""
import pathlib
import re
import sys


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    src = pathlib.Path(sys.argv[1])
    vals = dict(re.findall(r"public const int (MAPNUM_\w+) = (\d+);", (src / "processing/common/SomVanillaValues.cs").read_text(encoding="utf-8-sig")))
    text = (src / "processing/hacks/openworld/MagicRopeRefactor.cs").read_text(encoding="utf-8-sig")
    table = {}
    for name, door in re.findall(r"mapToDoor\[(\w+)\]\s*=\s*(0[xX][0-9a-fA-F]+|\d+);", text):
        table[int(vals[name])] = int(door, 0)
    out = ["/* Generated by tools/gen_p4_hmisc_rope.py from MagicRopeRefactor.cs (Author: Moppleton); %d maps.  Do not edit. */" % len(table),
           "static const uint16_t sr_p4_hmisc_rope_doors[512] = {"]
    for i in range(0, 512, 16):
        out.append("  " + ",".join("0x%X" % table.get(j, 0) for j in range(i, i + 16)) + ",")
    out.append("};")
    pathlib.Path(sys.argv[2]).write_text("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
