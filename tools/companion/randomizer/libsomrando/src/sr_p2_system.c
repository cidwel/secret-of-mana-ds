#include <string.h>

#include "sr_core.h"

#define E(v) sr_emit(c, (v))
#define P(off, v) sr_poke(c, (off), (v))

static void sr_w4_emit_seq(struct sr_ctx *c, const uint8_t *p, size_t n) {
  for (size_t i = 0; i < n; i++) E(p[i]);
}
#define SEQ(...) \
  do { \
    static const uint8_t s_[] = {__VA_ARGS__}; \
    sr_w4_emit_seq(c, s_, sizeof s_); \
  } while (0)

#define SR_W4_DONT_AUTOSAVE 0x7E0439

int sr_hack_autosave(struct sr_ctx *c) {
  const char *mode = sr_settings_get(c->settings, "mode");
  if (!strcmp(mode, "open")) {
    if (!sr_settings_get_bool(c->settings, "opAutosave")) return 0;
  } else if (!strcmp(mode, "rando")) {
    if (!sr_settings_get_bool(c->settings, "rAutosave")) return 0;
  } else {
    return 0;
  }

  sr_ensure_space_in_bank(&c->working_offset, 800);

  P(0x1E7D6, 0x22);
  P(0x1E7D7, c->working_offset);
  P(0x1E7D8, c->working_offset >> 8);
  P(0x1E7D9, (c->working_offset >> 16) + 0xC0);
  P(0x1E7DA, 0xEA);
  P(0x1E7DB, 0xEA);

  /* replaced code: AND #03FF, STA $010E */
  SEQ(0x29, 0xFF, 0x03, 0x8D, 0x0E, 0x01);

  static const int skip_doors[] = {0x75, 0x82, 0x38, 0x200, 0x0C, 0x3B, 0x271, 0x2F, 0x154, 0x366, 0x304, 0x35D, 0xFA, 0x3DF,
                                   0x254, 0x1A3, 0x31a, 0x3c7, 0x20f, 0x84, 0x186, 0x211};

  /* do not save when everybody is dead */
  SEQ(0x48, 0xA9, 0x00, 0x00, 0x48);
  SEQ(0xAF, 0x00, 0xE0, 0x7E, 0x29, 0xFF, 0x00, 0xF0, 0x07, 0x68, 0x18, 0x6F, 0x82, 0xE1, 0x7E, 0x48);
  SEQ(0xAF, 0x00, 0xE2, 0x7E, 0x29, 0xFF, 0x00, 0xF0, 0x07, 0x68, 0x18, 0x6F, 0x82, 0xE3, 0x7E, 0x48);
  SEQ(0xAF, 0x00, 0xE4, 0x7E, 0x29, 0xFF, 0x00, 0xF0, 0x07, 0x68, 0x18, 0x6F, 0x82, 0xE5, 0x7E, 0x48);
  SEQ(0x68, 0xD0, 0x02, 0x68, 0x6B);
  SEQ(0x68);

  for (size_t i = 0; i < sizeof skip_doors / sizeof skip_doors[0]; i++) {
    int d = skip_doors[i];
    E(0xC9); E(d); E(d >> 8);
    E(0xD0); E(0x01);
    E(0x6B);
  }

  /* DONT_AUTOSAVE flag: skip once after loading the autosave */
  SEQ(0x48, 0xE2, 0x20);
  E(0xAF); E(SR_W4_DONT_AUTOSAVE); E(SR_W4_DONT_AUTOSAVE >> 8); E(SR_W4_DONT_AUTOSAVE >> 16);
  SEQ(0xC9, 0x01, 0xD0, 0x0A, 0xA9, 0x00);
  E(0x8F); E(SR_W4_DONT_AUTOSAVE); E(SR_W4_DONT_AUTOSAVE >> 8); E(SR_W4_DONT_AUTOSAVE >> 16);
  SEQ(0xC2, 0x20, 0x68, 0x6B);
  SEQ(0xC2, 0x20, 0x68);
  /* inside-house maps: read the target map of the door */
  SEQ(0x48, 0xDA, 0x0A, 0x0A, 0xAA, 0xBF, 0x00, 0x30, 0xC8, 0x29, 0xFF, 0x01);

  static const int dont_save_maps[] = {309, 314, 256, 8, 125, 126, 127, 124, 123, 122, 280, 363, 391, 298, 261, 360, 409};
  for (size_t i = 0; i < sizeof dont_save_maps / sizeof dont_save_maps[0]; i++) {
    int m = dont_save_maps[i];
    E(0xC9); E(m); E(m >> 8);
    E(0xD0); E(0x03);
    E(0xFA); E(0x68); E(0x6B);
  }

  /* search the target map's object list for bosses */
  SEQ(0x0A, 0xAA, 0xBF, 0x00, 0x40, 0xC8, 0xDF, 0x02, 0x40, 0xC8, 0xD0, 0x03, 0xFA, 0x68, 0x6B);
  SEQ(0x5A, 0xBF, 0x02, 0x70, 0xC8, 0x38, 0xFF, 0x00, 0x70, 0xC8, 0xA8, 0xBF, 0x00, 0x70, 0xC8, 0x18, 0x69, 0x08, 0x00, 0xAA);
  SEQ(0x8B, 0xE2, 0x20, 0xA9, 0xC8, 0x48, 0xAB, 0xC2, 0x20);
  SEQ(0x98, 0x38, 0xE9, 0x08, 0x00, 0x90, 0x1B, 0xA8, 0xC0, 0x00, 0x00, 0xF0, 0x15);
  SEQ(0xBD, 0x05, 0x00, 0x29, 0xFF, 0x00, 0xC9, 0x57, 0x00, 0x90, 0xE8, 0xC9, 0x80, 0x00, 0xB0, 0xE3);
  SEQ(0xAB, 0x7A, 0xFA, 0x68, 0x6B);
  SEQ(0xAB, 0x7A, 0xFA, 0x68);
  SEQ(0x8D, 0x5A, 0xA2, 0x48, 0xE2, 0x20, 0xA9, 0x03, 0x8D, 0x11, 0xA2, 0x22, 0xD6, 0x55, 0xC7, 0xA9, 0x00, 0x8F, 0xFF, 0x7F, 0x30,
      0xC2, 0x20, 0x68, 0x6B);

  /* "Autosave" as the save location name */
  int autosave_subr = c->working_offset;
  static const uint8_t autosave_text[] = {0x9B, 0x95, 0x94, 0x8F, 0x93, 0x81, 0x96, 0x85};
  for (size_t i = 0; i < sizeof autosave_text; i++) {
    E(0xA9); E(autosave_text[i]);
    SEQ(0x9F, 0x00, 0x9C, 0x7E, 0xE8);
  }
  SEQ(0xA9, 0x00, 0x9F, 0x00, 0x9C, 0x7E, 0xE8, 0x6B);

  int old_subr = c->working_offset;
  for (int i = 0x75A64; i <= 0x75A85; i++) {
    E(sr_peek(c, i));
    P(i, 0xEA);
  }
  E(0x6B);

  int off = 0x75A64;
  static const uint8_t head[] = {0xAD, 0x62, 0xA1, 0xC9, 0x03, 0xD0, 0x06, 0x22};
  for (size_t i = 0; i < sizeof head; i++) P(off++, head[i]);
  P(off++, autosave_subr);
  P(off++, autosave_subr >> 8);
  P(off++, (autosave_subr >> 16) + 0xC0);
  P(off++, 0x80);
  P(off++, 0x04);
  P(off++, 0x22);
  P(off++, old_subr);
  P(off++, old_subr >> 8);
  P(off++, (old_subr >> 16) + 0xC0);

  /* save menu without slot 4 */
  static const uint8_t new_save_menu[] = {0x04, 0x42, 0x03, 0x01, 0x80, 0x00, 0x02, 0x03, 0x41, 0x8E, 0x00, 0x04,
                                          0x15, 0x41, 0x0E, 0x02, 0x04, 0x15, 0x41, 0x8E, 0x03, 0x04, 0x15, 0x00};
  for (size_t i = 0; i < sizeof new_save_menu; i++) P(0x74F80 + (int)i, new_save_menu[i]);
  P(0x77812, 0x80);
  P(0x77813, 0x4F);

  /* loading: set the DONT_AUTOSAVE flag */
  P(0x755C7, 0x22);
  P(0x755C8, c->working_offset);
  P(0x755C9, c->working_offset >> 8);
  P(0x755CA, (c->working_offset >> 16) + 0xC0);
  E(0xA9); E(0x01);
  E(0x8F); E(SR_W4_DONT_AUTOSAVE); E(SR_W4_DONT_AUTOSAVE >> 8); E(SR_W4_DONT_AUTOSAVE >> 16);
  SEQ(0x22, 0x21, 0x00, 0xC0, 0x6B);

  /* menu construction: pick the most recent slot per menu */
  P(0x2456, 0x22);
  P(0x2457, c->working_offset);
  P(0x2458, c->working_offset >> 8);
  P(0x2459, (c->working_offset >> 16) + 0xC0);
  SEQ(0x8F, 0x0A, 0xA2, 0x7E, 0xC0, 0x66, 0x75, 0xD0, 0x06, 0xA9, 0x03, 0x8F, 0xFF, 0x7F, 0x30);
  SEQ(0xC0, 0x80, 0x4F, 0xD0, 0x0E, 0xAF, 0xFF, 0x7F, 0x30, 0xC9, 0x03, 0xD0, 0x06, 0xA9, 0x00, 0x8F, 0xFF, 0x7F, 0x30);
  E(0x6B);
  return 1;
}
